#!/usr/bin/env bash
# Rebuilds the list of Cloudflare proxy ranges nginx trusts for CF-Connecting-IP.
# Run as root; setup.sh installs it as a monthly cron job.
set -euo pipefail

out=/etc/nginx/conf.d/cloudflare-realip.conf
tmp=$(mktemp)

{
    echo "# Generated by cloudflare-realip.sh - do not edit"
    for list in ips-v4 ips-v6; do
        curl -fsS "https://www.cloudflare.com/$list" | while read -r range; do
            [ -n "$range" ] && echo "set_real_ip_from $range;"
        done
    done
    echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"

if ! grep -q set_real_ip_from "$tmp"; then
    echo "cloudflare-realip: empty range list, keeping $out" >&2
    rm -f "$tmp"
    exit 1
fi

install -m 644 "$tmp" "$out"
rm -f "$tmp"
# starts nginx if it isn't running yet (first setup)
nginx -t && systemctl reload-or-restart nginx
